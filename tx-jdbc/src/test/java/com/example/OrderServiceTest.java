package com.example;

import io.github.fludakit.jdbc.JdbcClient;
import io.github.fludakit.jdbc.cdi.ConverterRegistryProducer;
import io.github.fludakit.jdbc.cdi.JdbcClientProducer;
import io.github.fludakit.tx.cdi.TransactionalCdiExtension;
import io.github.fludakit.tx.cdi.TransactionalInterceptor;
import io.github.fludakit.tx.jdbc.JdbcTransactionManagerProducer;
import org.jboss.weld.junit5.WeldInitiator;
import org.jboss.weld.junit5.WeldJunit5Extension;
import org.jboss.weld.junit5.WeldSetup;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;

import javax.sql.DataSource;
import jakarta.inject.Inject;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

@ExtendWith(WeldJunit5Extension.class)
class OrderServiceTest {

    @WeldSetup
    WeldInitiator setup = WeldInitiator
            .from(JdbcClientProducer.class, ConverterRegistryProducer.class, DataSourceProducer.class,
                    OrderService.class, JdbcTransactionManagerProducer.class, TransactionalInterceptor.class,
                    TransactionalCdiExtension.class)
            .build();

    @Inject
    JdbcClient client;

    @Inject
    OrderService orders;

    @Inject
    DataSource dataSource;

    @BeforeEach
    void setUp() throws Exception {
        try (var conn = dataSource.getConnection(); var stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS orders");
            stmt.execute("DROP TABLE IF EXISTS products");
            stmt.execute("CREATE TABLE orders ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "product_id BIGINT NOT NULL, "
                    + "quantity INTEGER NOT NULL, "
                    + "status VARCHAR(255) NOT NULL)");
            stmt.execute("CREATE TABLE products ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "sku VARCHAR(255) NOT NULL, "
                    + "stock INTEGER NOT NULL)");
            stmt.execute("INSERT INTO products (sku, stock) VALUES ('book-1', 5)");
        }
    }

    @Test
    void placeOrderDecrementsTheCatalogStockAndCreatesTheOrder() {
        Order order = orders.placeOrder("book-1", 2);

        assertEquals(3, stockOf("book-1"));
        assertEquals(1L, order.productId());
        assertEquals(2, order.quantity());
        assertEquals(OrderService.STATUS_CREATED, order.status());
    }

    @Test
    void placeOrderBeyondStockFailsAndLeavesNoTrace() {
        assertThrows(OutOfStockException.class, () -> orders.placeOrder("book-1", 6));

        assertEquals(5, stockOf("book-1"));
        long orders = client.sql("SELECT COUNT(*) FROM orders").query(Long.class).single();
        assertEquals(0L, orders);
    }

    @Test
    void orderLifecycleTransitions() {
        Order order = orders.placeOrder("book-1", 1);
        orders.payOrder(order.id());
        orders.shipOrder(order.id());
        assertEquals(OrderService.STATUS_SHIPPED, orders.findOrder(order.id()).status());
    }

    @Test
    void cancellingAnOrderReturnsItsStock() {
        Order order = orders.placeOrder("book-1", 2);
        assertEquals(3, stockOf("book-1"));

        orders.cancelOrder(order.id());

        assertEquals(5, stockOf("book-1"));
        assertEquals(OrderService.STATUS_CANCELLED, orders.findOrder(order.id()).status());
    }

    private int stockOf(String sku) {
        return client.sql("SELECT id, stock FROM products WHERE sku = :sku")
                .param("sku", sku)
                .query(Stock.class)
                .single()
                .stock();
    }
}
