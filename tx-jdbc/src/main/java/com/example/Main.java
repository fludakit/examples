package com.example;

import io.github.fludakit.jdbc.JdbcClient;
import org.jboss.weld.environment.se.Weld;
import org.jboss.weld.environment.se.WeldContainer;

import java.sql.Connection;
import java.sql.Statement;

import javax.sql.DataSource;

/**
 * Runs the ecommerce flow end to end: place an order, cancel it (stock returns), place another
 * one, pay and ship it, and finally show an out-of-stock order being rejected without touching
 * the catalog.
 */
public class Main {

    public static void main(String[] args) throws Exception {
        try (WeldContainer container = new Weld().initialize()) {
            DataSource dataSource = container.select(DataSource.class).get();
            try (Connection connection = dataSource.getConnection();
                 Statement statement = connection.createStatement()) {
                statement.execute("CREATE TABLE products ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "sku VARCHAR(255) NOT NULL, "
                        + "stock INTEGER NOT NULL)");
                statement.execute("CREATE TABLE orders ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "product_id BIGINT NOT NULL, "
                        + "quantity INTEGER NOT NULL, "
                        + "status VARCHAR(255) NOT NULL)");
            }

            JdbcClient client = container.select(JdbcClient.class).get();
            client.sql("INSERT INTO products (sku, stock) VALUES (:sku, :stock)")
                    .param("sku", "book-1")
                    .param("stock", 5)
                    .update();

            OrderService orders = container.select(OrderService.class).get();

            Order first = orders.placeOrder("book-1", 2);
            System.out.println("placed    " + first + ", stock left " + stockOf(client, "book-1"));

            System.out.println("cancelled " + orders.cancelOrder(first.id()));
            System.out.println("stock back to " + stockOf(client, "book-1"));

            Order second = orders.placeOrder("book-1", 1);
            orders.payOrder(second.id());
            orders.shipOrder(second.id());
            System.out.println("shipped   " + orders.findOrder(second.id()));

            try {
                orders.placeOrder("book-1", 999);
                System.out.println("unexpected: the order should have been rejected");
            } catch (OutOfStockException e) {
                System.out.println("rejected  " + e.getMessage());
            }
            System.out.println("stock after rejected order " + stockOf(client, "book-1"));
        }
    }

    private static int stockOf(JdbcClient client, String sku) {
        return client.sql("SELECT id, stock FROM products WHERE sku = :sku")
                .param("sku", sku)
                .query(Stock.class)
                .single()
                .stock();
    }
}
