package com.example;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Produces;
import org.h2.jdbcx.JdbcDataSource;

import javax.sql.DataSource;
import java.sql.Connection;

/**
 * A single in-memory H2 {@code DataSource} for the query-by-method-name example.
 *
 * <p>{@code DATABASE_TO_LOWER=TRUE} is not decoration: the processor quotes every identifier in
 * lowercase, so a table the DDL created as uppercase {@code TASK} would never match the quoted
 * {@code "task"} the generated SQL asks for. Starting from {@code DROP ALL OBJECTS} keeps the schema
 * clean when Weld restarts a container per test method against the same named database.</p>
 */
@ApplicationScoped
public class DataSourceProducer {

    @Produces
    @ApplicationScoped
    public DataSource dataSource() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:data-qbn;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE");
        try (Connection c = ds.getConnection()) {
            for (String stmt : new String[]{
                    "DROP ALL OBJECTS",
                    "CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(255), status VARCHAR(50))"
            }) {
                c.createStatement().execute(stmt);
            }
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
        return ds;
    }
}
