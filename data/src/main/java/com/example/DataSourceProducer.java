package com.example;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Produces;
import org.h2.jdbcx.JdbcDataSource;

import javax.sql.DataSource;
import java.sql.Connection;

/**
 * A single in-memory H2 {@code DataSource}.
 *
 * <p>{@code DATABASE_TO_LOWER=TRUE} is not decoration: the processor quotes every identifier in
 * lowercase, so a table the DDL created as uppercase {@code CUSTOMERS} would never match the quoted
 * {@code "customers"} the generated SQL asks for. Table names are the plural of the entity name.
 * Starting from {@code DROP ALL OBJECTS} keeps the
 * schema clean when Weld restarts a container per test method against the same named database.</p>
 */
@ApplicationScoped
public class DataSourceProducer {

    @Produces
    @ApplicationScoped
    public DataSource dataSource() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:data;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE");
        try (Connection c = ds.getConnection()) {
            for (String stmt : new String[]{
                    "DROP ALL OBJECTS",
                    "CREATE TABLE customers (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255), email VARCHAR(255))",
                    "CREATE TABLE products (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255), price DECIMAL(10,2))",
                    "CREATE TABLE \"orders\" (id BIGINT AUTO_INCREMENT PRIMARY KEY, amount DECIMAL(10,2), customer_id BIGINT)",
                    "CREATE TABLE order_items (order_id BIGINT, product_id BIGINT, quantity INT)",
                    "CREATE TABLE authors (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100))",
                    "CREATE TABLE books (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(100), author_id BIGINT)",
                    "CREATE TABLE teams (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100))",
                    "CREATE TABLE players (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100), team_id BIGINT)"
            }) {
                c.createStatement().execute(stmt);
            }
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
        return ds;
    }
}
