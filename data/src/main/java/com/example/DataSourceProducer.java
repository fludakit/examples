package com.example;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Produces;
import org.h2.jdbcx.JdbcDataSource;

import javax.sql.DataSource;
import java.sql.Connection;

/**
 * A single in-memory H2 {@code DataSource}.
 *
 * <p>{@code DATABASE_TO_LOWER=TRUE} is not decoration: the processor quotes every identifier in
 * lowercase, so a table the DDL created as uppercase {@code CUSTOMER} would never match the quoted
 * {@code "customer"} the generated SQL asks for. Starting from {@code DROP ALL OBJECTS} keeps the
 * schema clean when Weld restarts a container per test method against the same named database.</p>
 */
@ApplicationScoped
public class DataSourceProducer {

    @Produces
    @ApplicationScoped
    public DataSource dataSource() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:data;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE");
        try (Connection c = ds.getConnection()) {
            for (String stmt : new String[]{
                    "DROP ALL OBJECTS",
                    "CREATE TABLE customer (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255), email VARCHAR(255))",
                    "CREATE TABLE product (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255), price DECIMAL(10,2))",
                    "CREATE TABLE \"order\" (id BIGINT AUTO_INCREMENT PRIMARY KEY, amount DECIMAL(10,2), customer_id BIGINT)",
                    "CREATE TABLE order_order_items (order_id BIGINT, product_id BIGINT, quantity INT)",
                    "CREATE TABLE author (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100))",
                    "CREATE TABLE book (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(100), author_id BIGINT)",
                    "CREATE TABLE team (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100))",
                    "CREATE TABLE player (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100), team_id BIGINT)"
            }) {
                c.createStatement().execute(stmt);
            }
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
        return ds;
    }
}
