package com.example;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Produces;
import org.h2.jdbcx.JdbcDataSource;

import javax.sql.DataSource;
import java.sql.Connection;

/**
 * A single in-memory H2 {@code DataSource} for the CV aggregate example.
 *
 * <p>{@code DATABASE_TO_LOWER=TRUE} is not decoration: the processor quotes every identifier in
 * lowercase, so a table the DDL created as uppercase {@code PROFILE} would never match the quoted
 * {@code "profile"} the generated SQL asks for. {@code "value"} and {@code "year"} are H2 2.x reserved
 * words — created quoted lowercase to match the generated quoted SQL. Starting from
 * {@code DROP ALL OBJECTS} keeps the schema clean when Weld restarts a container per test method.</p>
 */
@ApplicationScoped
public class DataSourceProducer {

    @Produces
    @ApplicationScoped
    public DataSource dataSource() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:data-aggregate;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE");
        try (Connection c = ds.getConnection()) {
            for (String stmt : new String[]{
                    "DROP ALL OBJECTS",
                    "CREATE TABLE profile (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " full_name VARCHAR(255),"
                            + " address_city VARCHAR(100), address_zip INTEGER,"
                            + " address_point_lat DOUBLE PRECISION, address_point_lng DOUBLE PRECISION)",
                    "CREATE TABLE work_experience (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " company VARCHAR(255), year_start INT, year_end INT, profile_id BIGINT)",
                    "CREATE TABLE education (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " institution VARCHAR(255), degree VARCHAR(255), \"year\" INT, profile_id BIGINT)",
                    "CREATE TABLE profile_contacts (profile_id BIGINT, kind VARCHAR(100), \"value\" VARCHAR(255))"
            }) {
                c.createStatement().execute(stmt);
            }
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
        return ds;
    }
}
